//! Acciones semánticas. El keymap TOML nombra estas ids en string.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Action {
    CursorLeft,
    CursorRight,
    CursorUp,
    CursorDown,
    WordNext,
    WordPrev,
    LineStart,
    LineEnd,
    FileStart,
    FileEnd,
    InsertMode,
    InsertLineStart,
    InsertLineEnd,
    OpenBelow,
    OpenAbove,
    DeleteChar,
    DeleteCharBack,
    DeleteLine,
    Undo,
    Redo,
    SearchPrompt,
    SearchNext,
    SearchPrev,
    Save,
    Quit,
    NormalMode,
    SplitVert,
    SplitHoriz,
    ClosePane,
    FocusLeft,
    FocusRight,
    FocusUp,
    FocusDown,
    FindFile,
    CursorStyleNext,
    Hover,
    GotoDef,
    ToggleExplorer,
    TabNext,
    TabPrev,
    CloseBuffer,
    ToggleProblems,
    ToggleAi,
    AiContext,
    VisualMode,
    VisualLineMode,
    VisualChar,
    VisualLine,
    VisualDelete,
    VisualYank,
    VisualIndent,
    VisualDedent,
    VisualComment,
    YankLine,
    PasteAfter,
    BracketMatch,
    ReplacePrompt,
    GotoLinePrompt,
    CommentLine,
    MoveLinesDown,
    MoveLinesUp,
}

pub fn parse(id: &str) -> Option<Action> {
    let a = match id {
        "cursor_left" => Action::CursorLeft,
        "cursor_right" => Action::CursorRight,
        "cursor_up" => Action::CursorUp,
        "cursor_down" => Action::CursorDown,
        "word_next" => Action::WordNext,
        "word_prev" => Action::WordPrev,
        "line_start" => Action::LineStart,
        "line_end" => Action::LineEnd,
        "file_start" => Action::FileStart,
        "file_end" => Action::FileEnd,
        "insert_mode" => Action::InsertMode,
        "insert_line_start" => Action::InsertLineStart,
        "insert_line_end" => Action::InsertLineEnd,
        "open_below" => Action::OpenBelow,
        "open_above" => Action::OpenAbove,
        "delete_char" => Action::DeleteChar,
        "delete_char_back" => Action::DeleteCharBack,
        "delete_line" => Action::DeleteLine,
        "undo" => Action::Undo,
        "redo" => Action::Redo,
        "search_prompt" => Action::SearchPrompt,
        "search_next" => Action::SearchNext,
        "search_prev" => Action::SearchPrev,
        "save" => Action::Save,
        "quit" => Action::Quit,
        "normal_mode" => Action::NormalMode,
        "split_vertical" => Action::SplitVert,
        "split_horizontal" => Action::SplitHoriz,
        "close_pane" => Action::ClosePane,
        "focus_left" => Action::FocusLeft,
        "focus_right" => Action::FocusRight,
        "focus_up" => Action::FocusUp,
        "focus_down" => Action::FocusDown,
        "find_file" => Action::FindFile,
        "cursor_style_next" => Action::CursorStyleNext,
        "hover" => Action::Hover,
        "goto_definition" => Action::GotoDef,
        "toggle_explorer" => Action::ToggleExplorer,
        "tab_next" => Action::TabNext,
        "tab_prev" => Action::TabPrev,
        "close_buffer" => Action::CloseBuffer,
        "toggle_problems" => Action::ToggleProblems,
        "toggle_ai" => Action::ToggleAi,
        "ai_context" => Action::AiContext,
        "visual_mode" => Action::VisualMode,
        "visual_line_mode" => Action::VisualLineMode,
        "visual_char" => Action::VisualChar,
        "visual_line" => Action::VisualLine,
        "visual_delete" => Action::VisualDelete,
        "visual_yank" => Action::VisualYank,
        "visual_indent" => Action::VisualIndent,
        "visual_dedent" => Action::VisualDedent,
        "visual_comment" => Action::VisualComment,
        "yank_line" => Action::YankLine,
        "paste_after" => Action::PasteAfter,
        "bracket_match" => Action::BracketMatch,
        "replace_prompt" => Action::ReplacePrompt,
        "goto_line_prompt" => Action::GotoLinePrompt,
        "comment_line" => Action::CommentLine,
        "move_lines_down" => Action::MoveLinesDown,
        "move_lines_up" => Action::MoveLinesUp,
        _ => return None,
    };
    Some(a)
}
